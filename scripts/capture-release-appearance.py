#!/usr/bin/env python3
"""Capture the release owner's appearance settings without personal data."""

import argparse
import json
import plistlib
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Sources/TaskDock/ReleaseAppearanceSnapshot.swift"
APP_PLIST = ROOT / "AppBundle/TaskDock.app/Contents/Info.plist"

# Explicit allowlist: layout and visual controls only. Never copy favorites,
# folders, window history, licensing, hidden entries or feature permissions.
APPEARANCE_DEFAULTS = {
    "floatingBubbleBackgroundTransparencyV1": 0.0,
    "smallBubbleFontSizeV1": 12.0,
    "smallBubbleIconGapV1": 3.0,
    "taskbarBlackBackgroundTransparencyV1": 1.0,
    "taskbarItemHazeStrengthV1": 1.0,
    "taskdock.pointerAvoidanceAnimationDurationV1": 0.24,
    "taskdock.pointerAvoidanceTriggerDelayV1": 0.0,
    "taskdock.tiledAvoidanceTriggerDelayV1": 0.0,
    "taskdock.magnificationPushesTasksV1": False,
    "taskdock.customGlassClarityV1": 1.0,
    "taskdock.dockCompanionCollapseThreshold": 3,
    "taskdock.dockCompanionMinimumWindowCount": 2,
    "taskdock.dockCompanionOverlayEnabled": False,
    "taskdock.dockCompanionShowsBottomBar": True,
    "taskdock.dockCompanionShowsRecentWindows": True,
    "taskdock.experimentalActiveGlassV1": False,
    "taskdock.favoriteMagnificationEnabled": True,
    "taskdock.favoriteMagnificationScale": 2.0,
    "taskdock.layoutMode": "taskbar",
    "taskdock.mode.dockCompanion.nonSelectedItemTransparency": 0.35,
    "taskdock.taskItemHighlightStyle": "white",
    "taskdock.taskbarBackgroundTransparency": 0.0,
    "taskdock.taskbarCollapseSameAppWindows": True,
    "taskdock.taskbarHeight": 50.0,
    "taskdock.taskbarItemFontSize": 8.0,
    "taskdock.taskbarItemWidthMode": "adaptive",
    "taskdock.taskbarLeadingInset": 88.0,
}


def swift_literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (float, int)):
        return repr(value)
    raise TypeError(f"Unsupported appearance value: {type(value).__name__}")


def render() -> str:
    with APP_PLIST.open("rb") as stream:
        version = plistlib.load(stream)["CFBundleShortVersionString"]
    exported = subprocess.run(
        ["defaults", "export", "com.taskdock.app", "-"],
        check=True, capture_output=True,
    ).stdout
    local = plistlib.loads(exported)
    values = {}
    for key, fallback in APPEARANCE_DEFAULTS.items():
        value = local.get(key, fallback)
        if key == "taskdock.taskbarItemWidthMode":
            value = "adaptive"
        elif key == "taskdock.taskbarCollapseSameAppWindows":
            value = False
        if type(value) is not type(fallback):
            raise TypeError(f"Invalid type for {key}: {type(value).__name__}")
        values[key] = value
    lines = [
        "// Generated by scripts/capture-release-appearance.py on the main Mac.",
        "// Portable appearance only; do not add personal data or edit by hand.",
        "import Foundation",
        "",
        "enum ReleaseAppearanceSnapshot {",
        f"    static let version = {swift_literal(version)}",
        "    static let values: [String: Any] = [",
    ]
    lines.extend(f"        {swift_literal(key)}: {swift_literal(value)}," for key, value in sorted(values.items()))
    lines.extend(["    ]", "}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.write_text(expected)
        print(f"Captured {len(APPEARANCE_DEFAULTS)} appearance settings for release")
        return 0
    if not OUTPUT.exists() or OUTPUT.read_text() != expected:
        print("Appearance snapshot is stale. On the main Mac, run:", file=sys.stderr)
        print("python3 scripts/capture-release-appearance.py --write", file=sys.stderr)
        return 1
    print("RELEASE_APPEARANCE_SNAPSHOT_OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
